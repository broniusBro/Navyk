def main() -> None:
    path = ROOT / "content" / "course.json"
    course = json.loads(path.read_text(encoding="utf-8"))
    course["version"] = "1.0.0"
    course["language"] = {"target": "pl", "base": "ru"}
    course["exercise_types"] = EXERCISE_TYPES
    course.pop("principles", None)
    levels = []
    for li, (lid, title, goal, modules) in enumerate(LEVELS):
        mods = []
        for mid, mtitle, lessons in modules:
            ls = []
            for n, (ltitle, lgoal) in enumerate(lessons, 1):
                ls.append({
                    "id": f"{mid}.{n}",
                    "title": {"ru": ltitle},
                    "goal": lgoal,
                    # бесплатно всё; без аккаунта открыт первый модуль, дальше — бесплатная регистрация
                    "free_preview": mid == "a1m1",
                    "volatile": False,
                })
            mods.append({"id": mid, "title": {"ru": mtitle}, "lessons": ls})
        levels.append({"id": lid, "title": {"ru": title}, "goal": goal, "modules": mods})
    course["levels"] = levels
    path.write_text(json.dumps(course, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    n = sum(len(m["lessons"]) for l in levels for m in l["modules"])
    print(f"course.json: {len(levels)} уровня, {n} уроков")


if __name__ == "__main__":
    main()
